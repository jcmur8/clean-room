export function localized(record, field) {
  if (!record) return "";
  const alt = field + "Es";
  return current === "es"
    ? record[alt] || record[field] || ""
    : record[field] || record[alt] || "";
}
export function modeName(mode) {
  if (!mode) return t("battle");
  if (mode.nameEs || mode.name) return localized(mode, "name");
  const key = { quick: "quick", normal: "normal", deep: "deep" }[mode.id];
  return key ? t(key) : mode.id;
}
export function zoneName(zone) {
  if (!zone) return "";
  return localized(zone, "name");
}
